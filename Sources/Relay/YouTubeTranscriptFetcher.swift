import Foundation

/// Direct on-device YouTube caption discovery and transcript extraction (`SUM-10`).
/// Never routes URLs through Supadata or any third-party relay.
nonisolated enum YouTubeTranscriptFetcher {
    struct Transcript: Sendable, Equatable {
        let videoID: String
        let title: String?
        let languageCode: String
        let isAutoGenerated: Bool
        let text: String
        let segmentCount: Int
        let truncated: Bool
    }

    struct Segment: Sendable, Equatable {
        let startSeconds: Double
        let text: String
    }

    typealias HTTPTransport = @Sendable (URLRequest) async throws -> (Data, URLResponse)

    static let maximumTranscriptBytes = 64_000

    /// Returns `true` when `rawURL` points to a canonical YouTube video with a valid 11-character ID.
    static func isYouTubeVideo(_ rawURL: String) -> Bool {
        videoID(from: rawURL) != nil
    }

    /// Extracts the canonical 11-character YouTube video ID from `/watch?v=`, `youtu.be/`,
    /// `/shorts/`, `/live/`, or `/embed/` URLs. Rejects channel, feed, search, or malformed IDs.
    static func videoID(from rawURL: String) -> String? {
        guard let components = URLComponents(string: rawURL.trimmingCharacters(in: .whitespacesAndNewlines)),
              let scheme = components.scheme?.lowercased(),
              scheme == "https" || scheme == "http",
              let rawHost = components.host?.lowercased() else {
            return nil
        }

        let host = rawHost.hasPrefix("www.") ? String(rawHost.dropFirst(4)) : rawHost
        let pathSegments = components.path.split(separator: "/").map(String.init)

        let candidate: String?
        if host == "youtu.be" {
            candidate = pathSegments.first
        } else if host == "youtube.com" || host == "m.youtube.com" || host == "music.youtube.com" || host == "youtube-nocookie.com" {
            if components.path == "/watch" || pathSegments.first == "watch" {
                candidate = components.queryItems?.first(where: { $0.name == "v" })?.value
            } else if pathSegments.count >= 2, ["shorts", "live", "embed", "v"].contains(pathSegments[0]) {
                candidate = pathSegments[1]
            } else {
                candidate = nil
            }
        } else {
            candidate = nil
        }

        guard let id = candidate, isValidVideoID(id) else {
            return nil
        }
        return id
    }

    static func isValidVideoID(_ candidate: String) -> Bool {
        guard candidate.utf8.count == 11 else { return false }
        return candidate.unicodeScalars.allSatisfy { scalar in
            switch scalar.value {
            case 0x30...0x39, 0x41...0x5A, 0x61...0x7A, 0x2D, 0x5F:
                return true
            default:
                return false
            }
        }
    }

    static let iosClientUserAgent = "com.google.ios.youtube/20.10.4 (iPhone16,2; U; CPU iOS 18_3_2 like Mac OS X)"
    static let webSafariUserAgent = "Mozilla/5.0 (Macintosh; Intel Mac OS X 15_0) AppleWebKit/605.1.15 (KHTML, like Gecko) Version/18.0 Safari/605.1.15"
    private static let defaultAcceptLanguage = "en-US,en;q=0.9"

    /// Fetches and formats the native caption track for a YouTube URL when available.
    static func fetchTranscript(
        for rawURL: String,
        preferredLanguages: [String] = ["en", "en-US", "en-GB"],
        maximumBytes: Int = maximumTranscriptBytes,
        transport: HTTPTransport = defaultTransport
    ) async throws -> Transcript? {
        guard let id = videoID(from: rawURL) else { return nil }
        try Task.checkCancellation()

        // 1. Try iOS Innertube player endpoint first (returns directly downloadable captionTracks without browser PoToken gating).
        do {
            if let innertubePlayer = try await fetchInnertubePlayerJSON(videoID: id, transport: transport),
               let transcript = try await transcriptFromPlayer(
                   innertubePlayer,
                   videoID: id,
                   userAgent: iosClientUserAgent,
                   preferredLanguages: preferredLanguages,
                   maximumBytes: maximumBytes,
                   propagateTransportErrors: false,
                   transport: transport
               ) {
                return transcript
            }
        } catch is CancellationError {
            throw CancellationError()
        } catch let urlError as URLError where urlError.code == .cancelled {
            throw CancellationError()
        } catch {
            try Task.checkCancellation()
        }

        // 2. Fallback to canonical watch-page HTML ytInitialPlayerResponse (supports legacy responses and mock transports).
        do {
            guard let watchPlayer = try await fetchWatchPlayerJSON(videoID: id, transport: transport) else {
                return nil
            }
            return try await transcriptFromPlayer(
                watchPlayer,
                videoID: id,
                userAgent: webSafariUserAgent,
                preferredLanguages: preferredLanguages,
                maximumBytes: maximumBytes,
                propagateTransportErrors: true,
                transport: transport
            )
        } catch is CancellationError {
            throw CancellationError()
        } catch let urlError as URLError where urlError.code == .cancelled {
            throw CancellationError()
        }
    }

    // MARK: - Player Response & Track Parsing (Unit-Testable)

    struct CaptionTrackDescriptor: Sendable, Equatable {
        let baseURL: String
        let languageCode: String
        let isAutoGenerated: Bool
    }

    static func extractPlayerResponseJSON(fromWatchHTML html: String) -> [String: Any]? {
        let markers = ["var ytInitialPlayerResponse = ", "ytInitialPlayerResponse = "]
        for marker in markers {
            guard let markerRange = html.range(of: marker) else { continue }
            let tail = html[markerRange.upperBound...]
            guard let jsonSlice = extractBalancedJSONObject(from: tail),
                  let data = jsonSlice.data(using: .utf8),
                  let obj = try? JSONSerialization.jsonObject(with: data) as? [String: Any] else {
                continue
            }
            return obj
        }
        return nil
    }

    static func selectCaptionTrack(
        from playerResponse: [String: Any],
        preferredLanguages: [String] = ["en", "en-US", "en-GB"]
    ) -> CaptionTrackDescriptor? {
        guard let captions = playerResponse["captions"] as? [String: Any],
              let renderer = captions["playerCaptionsTracklistRenderer"] as? [String: Any],
              let rawTracks = renderer["captionTracks"] as? [[String: Any]],
              !rawTracks.isEmpty else {
            return nil
        }

        let tracks: [CaptionTrackDescriptor] = rawTracks.compactMap { dict in
            guard let baseURL = dict["baseUrl"] as? String, !baseURL.isEmpty else { return nil }
            let languageCode = (dict["languageCode"] as? String) ?? "und"
            let kind = (dict["kind"] as? String) ?? ""
            return CaptionTrackDescriptor(
                baseURL: baseURL,
                languageCode: languageCode,
                isAutoGenerated: kind.lowercased() == "asr"
            )
        }
        guard !tracks.isEmpty else { return nil }

        // Prefer manual captions in preferred language, then ASR in preferred language,
        // then manual in any language, then first available track.
        for pref in preferredLanguages {
            if let exactManual = tracks.first(where: { !$0.isAutoGenerated && $0.languageCode.caseInsensitiveCompare(pref) == .orderedSame }) {
                return exactManual
            }
            if let prefixManual = tracks.first(where: { !$0.isAutoGenerated && $0.languageCode.lowercased().hasPrefix(pref.lowercased() + "-") }) {
                return prefixManual
            }
        }
        for pref in preferredLanguages {
            if let exactASR = tracks.first(where: { $0.languageCode.caseInsensitiveCompare(pref) == .orderedSame }) {
                return exactASR
            }
            if let prefixASR = tracks.first(where: { $0.languageCode.lowercased().hasPrefix(pref.lowercased() + "-") }) {
                return prefixASR
            }
        }
        return tracks.first(where: { !$0.isAutoGenerated }) ?? tracks.first
    }

    static func parseCaptionPayload(_ data: Data) -> [Segment] {
        let text = String(decoding: data, as: UTF8.self).trimmingCharacters(in: .whitespacesAndNewlines)
        if text.hasPrefix("{") {
            let jsonSegments = parseJSON3Transcript(data)
            if !jsonSegments.isEmpty { return jsonSegments }
        }
        return parseTranscriptXML(text)
    }

    static func parseJSON3Transcript(_ data: Data) -> [Segment] {
        guard let root = try? JSONSerialization.jsonObject(with: data) as? [String: Any],
              let events = root["events"] as? [[String: Any]] else {
            return []
        }
        var segments: [Segment] = []
        for event in events {
            guard let segs = event["segs"] as? [[String: Any]] else { continue }
            let startMs = (event["tStartMs"] as? Double) ?? Double((event["tStartMs"] as? Int) ?? 0)
            let combined = segs.compactMap { $0["utf8"] as? String }.joined()
            let cleaned = normalizeCaptionLine(combined)
            if !cleaned.isEmpty {
                segments.append(Segment(startSeconds: max(0, startMs / 1000.0), text: cleaned))
            }
        }
        return coalesceSegments(segments)
    }

    static func parseTranscriptXML(_ xml: String) -> [Segment] {
        var segments: [Segment] = []
        let pattern = #"<text\b([^>]*)>([\s\S]*?)</text>"#
        guard let regex = try? NSRegularExpression(pattern: pattern, options: [.caseInsensitive]) else {
            return []
        }
        let ns = xml as NSString
        let matches = regex.matches(in: xml, range: NSRange(location: 0, length: ns.length))
        for match in matches where match.numberOfRanges >= 3 {
            let attrs = ns.substring(with: match.range(at: 1))
            let rawBody = ns.substring(with: match.range(at: 2))
            let start = extractStartAttribute(from: attrs) ?? 0
            let decoded = decodeHTMLEntities(rawBody)
            let cleaned = normalizeCaptionLine(decoded)
            if !cleaned.isEmpty {
                segments.append(Segment(startSeconds: max(0, start), text: cleaned))
            }
        }
        return coalesceSegments(segments)
    }

    static func formatSegments(_ segments: [Segment]) -> String {
        var lines: [String] = []
        var lastBucket = -1
        var currentLineParts: [String] = []
        var currentTimestamp = 0.0

        func flush() {
            guard !currentLineParts.isEmpty else { return }
            let joined = currentLineParts.joined(separator: " ")
            lines.append("[\(formatTimestamp(currentTimestamp))] \(joined)")
            currentLineParts.removeAll(keepingCapacity: true)
        }

        for segment in segments {
            let bucket = Int(segment.startSeconds / 15.0)
            if bucket != lastBucket && !currentLineParts.isEmpty {
                flush()
            }
            if currentLineParts.isEmpty {
                currentTimestamp = segment.startSeconds
                lastBucket = bucket
            }
            currentLineParts.append(segment.text)
        }
        flush()
        return lines.joined(separator: "\n")
    }

    static func formatTimestamp(_ seconds: Double) -> String {
        let total = max(0, Int(seconds.rounded(.down)))
        let hours = total / 3600
        let minutes = (total % 3600) / 60
        let secs = total % 60
        if hours > 0 {
            return String(format: "%d:%02d:%02d", hours, minutes, secs)
        }
        return String(format: "%02d:%02d", minutes, secs)
    }

    // MARK: - Internal Helpers

    static let defaultTransport: HTTPTransport = { request in
        let config = URLSessionConfiguration.ephemeral
        config.httpCookieAcceptPolicy = .never
        config.httpShouldSetCookies = false
        config.timeoutIntervalForRequest = 10
        config.timeoutIntervalForResource = 15
        let session = URLSession(configuration: config)
        defer { session.finishTasksAndInvalidate() }
        return try await session.data(for: request)
    }

    static func fetchInnertubePlayerJSON(
        videoID: String,
        transport: HTTPTransport = defaultTransport
    ) async throws -> [String: Any]? {
        try Task.checkCancellation()
        guard let url = URL(string: "https://www.youtube.com/youtubei/v1/player?prettyPrint=false") else { return nil }
        var request = URLRequest(url: url, cachePolicy: .reloadIgnoringLocalCacheData, timeoutInterval: 10)
        request.httpMethod = "POST"
        request.httpShouldHandleCookies = false
        request.setValue("application/json", forHTTPHeaderField: "Content-Type")
        request.setValue(defaultAcceptLanguage, forHTTPHeaderField: "Accept-Language")
        request.setValue(iosClientUserAgent, forHTTPHeaderField: "User-Agent")
        let body: [String: Any] = [
            "videoId": videoID,
            "context": [
                "client": [
                    "clientName": "IOS",
                    "clientVersion": "20.10.4",
                    "deviceMake": "Apple",
                    "deviceModel": "iPhone16,2",
                    "osName": "iPhone",
                    "osVersion": "18.3.2.22D82",
                    "hl": "en",
                ]
            ],
        ]
        request.httpBody = try JSONSerialization.data(withJSONObject: body)
        let (data, response) = try await transport(request)
        try Task.checkCancellation()
        guard let http = response as? HTTPURLResponse,
              (200..<300).contains(http.statusCode),
              !data.isEmpty,
              data.count <= 4 * 1_024 * 1_024 else {
            return nil
        }
        return try? JSONSerialization.jsonObject(with: data) as? [String: Any]
    }

    private static func fetchWatchPlayerJSON(
        videoID: String,
        transport: HTTPTransport
    ) async throws -> [String: Any]? {
        try Task.checkCancellation()
        guard let watchURL = URL(string: "https://www.youtube.com/watch?v=\(videoID)&hl=en") else { return nil }
        var watchRequest = URLRequest(url: watchURL, cachePolicy: .reloadIgnoringLocalCacheData, timeoutInterval: 10)
        watchRequest.httpShouldHandleCookies = false
        watchRequest.setValue(defaultAcceptLanguage, forHTTPHeaderField: "Accept-Language")
        watchRequest.setValue(webSafariUserAgent, forHTTPHeaderField: "User-Agent")

        let (watchData, watchResponse) = try await transport(watchRequest)
        try Task.checkCancellation()
        guard let http = watchResponse as? HTTPURLResponse,
              (200..<300).contains(http.statusCode),
              !watchData.isEmpty,
              watchData.count <= 4 * 1_024 * 1_024 else {
            return nil
        }

        let html = String(decoding: watchData, as: UTF8.self)
        return extractPlayerResponseJSON(fromWatchHTML: html)
    }

    private static func transcriptFromPlayer(
        _ player: [String: Any],
        videoID: String,
        userAgent: String,
        preferredLanguages: [String],
        maximumBytes: Int,
        propagateTransportErrors: Bool,
        transport: HTTPTransport
    ) async throws -> Transcript? {
        guard let track = selectCaptionTrack(from: player, preferredLanguages: preferredLanguages) else {
            return nil
        }
        let segments = try await downloadCaptionSegments(
            for: track,
            userAgent: userAgent,
            propagateTransportErrors: propagateTransportErrors,
            transport: transport
        )
        guard !segments.isEmpty else { return nil }

        let formatted = formatSegments(segments)
        guard !formatted.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return nil }
        let bounded = DocumentSummarySource.excerpt(formatted, maximumBytes: maximumBytes)
        let wasTruncated = bounded.utf8.count < formatted.utf8.count

        return Transcript(
            videoID: videoID,
            title: extractVideoTitle(from: player),
            languageCode: track.languageCode,
            isAutoGenerated: track.isAutoGenerated,
            text: bounded,
            segmentCount: segments.count,
            truncated: wasTruncated
        )
    }

    private static func downloadCaptionSegments(
        for track: CaptionTrackDescriptor,
        userAgent: String,
        propagateTransportErrors: Bool,
        transport: HTTPTransport
    ) async throws -> [Segment] {
        guard let trackURL = validatedCaptionTrackURL(track.baseURL) else {
            return []
        }

        func requestTrackData(_ url: URL, propagateErrors: Bool) async throws -> Data? {
            try Task.checkCancellation()
            var trackRequest = URLRequest(url: url, cachePolicy: .reloadIgnoringLocalCacheData, timeoutInterval: 10)
            trackRequest.httpShouldHandleCookies = false
            trackRequest.setValue(defaultAcceptLanguage, forHTTPHeaderField: "Accept-Language")
            trackRequest.setValue(userAgent, forHTTPHeaderField: "User-Agent")
            do {
                let (trackData, trackResponse) = try await transport(trackRequest)
                try Task.checkCancellation()
                guard let trackHTTP = trackResponse as? HTTPURLResponse,
                      (200..<300).contains(trackHTTP.statusCode),
                      !trackData.isEmpty,
                      trackData.count <= 4 * 1_024 * 1_024 else {
                    return nil
                }
                return trackData
            } catch is CancellationError {
                throw CancellationError()
            } catch let urlError as URLError where urlError.code == .cancelled {
                throw CancellationError()
            } catch {
                try Task.checkCancellation()
                if propagateErrors {
                    throw error
                }
                return nil
            }
        }

        // Request fmt=json3 first while preserving existing percent-encoded signature parameters;
        // if empty or unparseable, retry the raw trackURL without fmt=json3 and parse XML.
        let json3URL = captionURLWithJSON3(trackURL)
        let hasDistinctRawFallback = json3URL != trackURL

        if let json3Data = try await requestTrackData(
            json3URL,
            propagateErrors: propagateTransportErrors && !hasDistinctRawFallback
        ) {
            let segments = parseCaptionPayload(json3Data)
            if !segments.isEmpty {
                return segments
            }
        }

        guard hasDistinctRawFallback,
              let rawData = try await requestTrackData(trackURL, propagateErrors: propagateTransportErrors) else {
            return []
        }
        let xmlText = String(decoding: rawData, as: UTF8.self)
        let xmlSegments = parseTranscriptXML(xmlText)
        if !xmlSegments.isEmpty {
            return xmlSegments
        }
        return parseCaptionPayload(rawData)
    }

    private static func captionURLWithJSON3(_ trackURL: URL) -> URL {
        guard var components = URLComponents(url: trackURL, resolvingAgainstBaseURL: false) else {
            return trackURL
        }
        let items = components.queryItems ?? []
        if items.contains(where: { $0.name == "fmt" && $0.value == "json3" }) {
            return trackURL
        }
        let existing = components.percentEncodedQuery ?? ""
        if items.contains(where: { $0.name == "fmt" }) {
            let filtered = existing
                .split(separator: "&", omittingEmptySubsequences: false)
                .filter { !$0.hasPrefix("fmt=") && $0 != "fmt" }
                .joined(separator: "&")
            components.percentEncodedQuery = filtered.isEmpty ? "fmt=json3" : "\(filtered)&fmt=json3"
        } else {
            components.percentEncodedQuery = existing.isEmpty ? "fmt=json3" : "\(existing)&fmt=json3"
        }
        return components.url ?? trackURL
    }

    private static func validatedCaptionTrackURL(_ raw: String) -> URL? {
        guard let components = URLComponents(string: raw),
              components.scheme?.lowercased() == "https",
              let host = components.host?.lowercased(),
              host == "www.youtube.com" || host == "youtube.com" || host.hasSuffix(".youtube.com") else {
            return nil
        }
        return components.url
    }

    private static func extractVideoTitle(from playerResponse: [String: Any]) -> String? {
        guard let details = playerResponse["videoDetails"] as? [String: Any],
              let title = details["title"] as? String,
              !title.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else {
            return nil
        }
        return title
    }

    private static func extractBalancedJSONObject(from substring: Substring) -> Substring? {
        guard let start = substring.firstIndex(of: "{") else { return nil }
        var depth = 0
        var inString = false
        var escaped = false
        var index = start
        var scannedBytes = 0
        while index < substring.endIndex, scannedBytes < 2_500_000 {
            let ch = substring[index]
            scannedBytes += 1
            if inString {
                if escaped {
                    escaped = false
                } else if ch == "\\" {
                    escaped = true
                } else if ch == "\"" {
                    inString = false
                }
            } else {
                if ch == "\"" {
                    inString = true
                } else if ch == "{" {
                    depth += 1
                } else if ch == "}" {
                    depth -= 1
                    if depth == 0 {
                        return substring[start...index]
                    }
                }
            }
            index = substring.index(after: index)
        }
        return nil
    }

    private static func extractStartAttribute(from attrs: String) -> Double? {
        guard let range = attrs.range(of: #"start\s*=\s*["']([0-9.]+)["']"#, options: .regularExpression) else {
            return nil
        }
        let matched = String(attrs[range])
        let digits = matched.filter { ("0"..."9").contains($0) || $0 == "." }
        return Double(digits)
    }

    static func decodeHTMLEntities(_ input: String) -> String {
        var out = input
            .replacingOccurrences(of: "&amp;", with: "&")
            .replacingOccurrences(of: "&lt;", with: "<")
            .replacingOccurrences(of: "&gt;", with: ">")
            .replacingOccurrences(of: "&quot;", with: "\"")
            .replacingOccurrences(of: "&#39;", with: "'")
            .replacingOccurrences(of: "&apos;", with: "'")
            .replacingOccurrences(of: "&nbsp;", with: " ")

        if let decRegex = try? NSRegularExpression(pattern: #"&#([0-9]{1,7});"#) {
            let matches = decRegex.matches(in: out, range: NSRange(location: 0, length: (out as NSString).length)).reversed()
            for match in matches where match.numberOfRanges >= 2 {
                let codeStr = (out as NSString).substring(with: match.range(at: 1))
                if let code = UInt32(codeStr), let scalar = Unicode.Scalar(code) {
                    out = (out as NSString).replacingCharacters(in: match.range, with: String(scalar))
                }
            }
        }
        if let hexRegex = try? NSRegularExpression(pattern: #"&#x([0-9a-fA-F]{1,6});"#) {
            let matches = hexRegex.matches(in: out, range: NSRange(location: 0, length: (out as NSString).length)).reversed()
            for match in matches where match.numberOfRanges >= 2 {
                let codeStr = (out as NSString).substring(with: match.range(at: 1))
                if let code = UInt32(codeStr, radix: 16), let scalar = Unicode.Scalar(code) {
                    out = (out as NSString).replacingCharacters(in: match.range, with: String(scalar))
                }
            }
        }
        return out
    }

    private static func normalizeCaptionLine(_ raw: String) -> String {
        let stripped = raw.unicodeScalars.filter { scalar in
            !(scalar.properties.generalCategory == .control && scalar != "\n" && scalar != "\t")
        }
        return String(String.UnicodeScalarView(stripped))
            .replacingOccurrences(of: "\n", with: " ")
            .split(whereSeparator: \.isWhitespace)
            .joined(separator: " ")
    }

    private static func coalesceSegments(_ segments: [Segment]) -> [Segment] {
        var result: [Segment] = []
        for segment in segments {
            if let last = result.last, last.text == segment.text, abs(segment.startSeconds - last.startSeconds) < 3.0 {
                continue
            }
            result.append(segment)
        }
        return result
    }
}
